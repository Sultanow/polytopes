#!/usr/bin/env python3
"""Produce 16 independently enumerated reflexive polygon classes and verified inclusions.

No network calls or third-party Python dependencies.
These representatives are generated by exact integer lattice arithmetic.
The finite search uses coordinates in [-3,3], and the output is cross-checked
against the independently known classification count 16; the count alone is
not offered as a proof that the search bound is sufficient.

Inclusions are searched among GL(2,Z) matrices with entries in [-8,8];
we deliberately publish only verified inclusions, not the assertion that
this matrix bound detects every conceivable embedding.
"""
import itertools
import json
from math import gcd
from pathlib import Path

BOUNDS = range(-3, 4)
POINTS = [(x, y) for x in BOUNDS for y in BOUNDS if (x, y) != (0, 0)]


def cross(o, a, b):
    return (a[0]-o[0])*(b[1]-o[1])-(a[1]-o[1])*(b[0]-o[0])


def hull(vertices):
    pts = sorted(set(vertices))
    if len(pts) < 3:
        return ()
    lower, upper = [], []
    for p in pts:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], p) <= 0:
            lower.pop()
        lower.append(p)
    for p in reversed(pts):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], p) <= 0:
            upper.pop()
        upper.append(p)
    return tuple(lower[:-1] + upper[:-1])


def is_reflexive(poly):
    if len(poly) < 3:
        return False
    # Primitive inward normal n to every facet satisfies <n, v>=-1.
    return all((-dy * a[0] + dx * a[1]) == -gcd(abs(dx), abs(dy))
               for a,b in zip(poly, poly[1:] + poly[:1])
               for dx,dy in [(b[0]-a[0], b[1]-a[1])])


def area_twice(poly):
    return sum(a[0]*b[1] - a[1]*b[0] for a,b in zip(poly,poly[1:]+poly[:1]))


def equivalent(p, q):
    if len(p) != len(q) or area_twice(p) != area_twice(q):
        return False
    target = set(q)
    a = p[0]
    for b in p[1:]:
        den = a[0]*b[1] - a[1]*b[0]
        if not den:
            continue
        for c,d in itertools.permutations(q,2):
            aa = c[0]*b[1] - d[0]*a[1]
            bb = d[0]*a[0] - c[0]*b[0]
            cc = c[1]*b[1] - d[1]*a[1]
            dd = d[1]*a[0] - c[1]*b[0]
            if any(k%den != 0 for k in (aa,bb,cc,dd)):
                continue
            aa,bb,cc,dd = (k//den for k in (aa,bb,cc,dd))
            if abs(aa*dd-bb*cc)==1 and {(aa*x+bb*y,cc*x+dd*y) for x,y in p} == target:
                return True
    return False


def add_unique(catalogue, poly):
    if any(equivalent(poly,old) for old in catalogue):
        return False
    catalogue.append(poly)
    return True


def enumeration():
    catalogue = []
    for points in itertools.combinations(POINTS,3):
        p = hull(points)
        if len(p)==3 and is_reflexive(p):
            add_unique(catalogue,p)
    for points in itertools.combinations(POINTS,4):
        p = hull(points)
        if len(p)==4 and is_reflexive(p):
            add_unique(catalogue,p)
    new = catalogue.copy()
    for vertex_count in (5,6,7):
        nxt = []
        for poly in new:
            for pt in POINTS:
                candidate=hull(poly+(pt,))
                if len(candidate)==vertex_count and is_reflexive(candidate) and add_unique(catalogue,candidate):
                    nxt.append(candidate)
        new=nxt
    catalogue.sort(key=lambda poly:(len(poly),area_twice(poly),poly))
    assert len(catalogue)==16, f"Expected 16 polygon classes, got {len(catalogue)}"
    return catalogue


def inside(point, poly):
    return all(cross(a,b,point)>=0 for a,b in zip(poly,poly[1:]+poly[:1]))


def transforms(bound=8):
    mats=[]
    for a,b,c,d in itertools.product(range(-bound,bound+1),repeat=4):
        if abs(a*d-b*c)==1:
            mats.append((a,b,c,d))
    mats.sort(key=lambda m:(sum(v*v for v in m),m[0]*m[3]-m[1]*m[2]<0,m))
    return mats


def find_inclusion(p,q,mats):
    for a,b,c,d in mats:
        mapped = [(a*x+b*y,c*x+d*y) for x,y in p]
        if all(inside(v,q) for v in mapped):
            return [a,b,c,d]
    return None


def main():
    polys=enumeration()
    mats=transforms()
    includes={}
    for i,p in enumerate(polys):
        for j,q in enumerate(polys):
            if area_twice(p)>=area_twice(q):
                continue
            mat=find_inclusion(p,q,mats)
            if mat is not None:
                includes[(i,j)]=mat
    covers=[]
    for (i,j),mat in includes.items():
        if not any((i,k) in includes and (k,j) in includes for k in range(len(polys))):
            covers.append({'from':f'P{i+1:02d}','to':f'P{j+1:02d}','matrix':mat})
    catalogue=[{'id':f'P{i+1:02d}','vertices':[list(x) for x in p],
                'vertex_count':len(p),'area_twice':area_twice(p)} for i,p in enumerate(polys)]
    path=Path(__file__).resolve().parents[1]/'src'/'data'/'reflexive-2d.json'
    path.parent.mkdir(parents=True,exist_ok=True)
    payload={'dimension':2,'count':16,'source':'Exact generated representatives; see scripts/generate_reflexive_2d.py',
             'polytopes':catalogue,'cover_edges':covers,
             'notes':'Each edge gives a verified GL(2,Z) embedding of the from-polytope into the to-polytope. The displayed relation is within this verified subset of cover candidates.'}
    path.write_text(json.dumps(payload,indent=2)+'\n',encoding='utf-8')
    print('Polygons:',len(polys),'verified inclusions:',len(includes),'covers:',len(covers))
    print('Saved:',path)

if __name__=='__main__': main()
